#!/usr/bin/env node
import { globSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Generate the two registries the component suite mounts through.
 *
 * **The types.** Playwright declares `interface Stories {}` empty and
 * `StoryId = keyof Stories | (string & {})`, which is declaration merging — the same door
 * `DialogRegistry` opens for dialog ids. Filling it gives a reader the list at the call site and
 * types each story's props from its own signature, so `mount('AlignSlideHarness', …)` is checked
 * rather than hoped. `typeof import('…')` rather than a top-level import: 196 imports in a `.d.ts`
 * would be 196 modules pulled into every program that reads it. One file per tsconfig scope,
 * because the root's `include` is `src/**` and the playground has its own.
 *
 * **The loaders.** One lazy `import()` per id, so a test page pulls in the harness it mounts and
 * nothing else. Globbing eagerly worked and cost twice the wall clock, plus every module-level side
 * effect in the app on every test page — `ThemeProvider` writes `--form-bg` inline on `:root` at
 * import, which outranks the stylesheet rule a template's dark mode keys on, and the dropdown's
 * scheme test went red on exactly that.
 *
 * A literal specifier per entry, because a bundler cannot follow `import(variable)`.
 */
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const EXPORTED = /^export (?:function|const) ([A-Za-z0-9_]+)/gm;
const SLASH = String.fromCharCode(47);

/** Where each scope's stories live, and where its type augmentation goes. */
const SCOPES = [
  {
    name: 'the library',
    glob: 'src/**/__tests__/**/*.story.tsx',
    types: 'src/__tests__/story-ids.d.ts',
  },
  {
    name: 'the playground',
    glob: 'playground/src/**/__tests__/**/*.story.tsx',
    types: 'playground/src/__tests__/story-ids.d.ts',
  },
];

/** `src/a/b.story.tsx` → `src/a/b`, with POSIX separators whatever the platform used. */
const posixify = (file) => {
  return file
    .split(sep)
    .join(SLASH)
    .replace(/\.tsx$/, '');
};

/** Every exported harness in a file, sorted, so a regenerate is a no-op when nothing moved. */
const harnessesIn = (file) => {
  return [...readFileSync(resolve(ROOT, file), 'utf8').matchAll(EXPORTED)]
    .map((match) => {
      return match[1];
    })
    .sort();
};

const loaders = [];
let total = 0;

for (const scope of SCOPES) {
  const files = globSync(scope.glob, { cwd: ROOT }).sort();
  const entries = [];

  for (const file of files) {
    const names = harnessesIn(file);
    if (names.length === 0) {
      continue;
    }

    // The type side is relative to its own `.d.ts` and extensionless — a type position, not a
    // runtime import.
    const fromTypes = posixify(relative(dirname(resolve(ROOT, scope.types)), resolve(ROOT, file)));
    const typeSpecifier = fromTypes.startsWith('.') ? fromTypes : `.${SLASH}${fromTypes}`;

    // The runtime side goes through the public specifier, never a deep relative climb — the rule
    // `playground/CLAUDE.md` states for everything reaching into the library.
    const posix = posixify(file);
    const runtimeSpecifier = posix.startsWith(`src${SLASH}`)
      ? `umbra${SLASH}${posix.slice(4)}`
      : `@${SLASH}${posix.slice(`playground${SLASH}src${SLASH}`.length)}`;

    for (const name of names) {
      entries.push(`    ${name}: (typeof import('${typeSpecifier}'))['${name}'];`);
      loaders.push(`  ${name}: () => {
    return import('${runtimeSpecifier}');
  },`);
    }
  }

  total += entries.length;
  const header = `// Generated by \`yarn story-ids\` — do not edit. ${entries.length} harnesses in ${scope.name}.`;
  writeFileSync(
    resolve(ROOT, scope.types),
    [
      header,
      '//',
      "// Fills Playwright's `Stories` interface so `mount('…')` offers the list and checks the props.",
      '// See scripts/generate-story-ids.mjs for why this is generated and why it is one file per scope.',
      '',
      "declare module '@playwright/test' {",
      '  interface Stories {',
      entries.join('\n'),
      '  }',
      '}',
      '',
      'export {};',
      '',
    ].join('\n'),
    'utf8'
  );
  console.log(`${scope.types}: ${entries.length} harnesses`);
}

writeFileSync(
  resolve(ROOT, 'playground/src/pages/stories/model/story-loaders.ts'),
  [
    `// Generated by \`yarn story-ids\` — do not edit. ${loaders.length} harnesses.`,
    '//',
    '// One lazy loader per story id, so a test page pulls in the harness it mounts and nothing else.',
    '// See scripts/generate-story-ids.mjs for why this is generated rather than globbed at run time.',
    '',
    'export const STORY_LOADERS: Readonly<Record<string, () => Promise<Record<string, unknown>>>> = {',
    loaders.join('\n'),
    '};',
    '',
  ].join('\n'),
  'utf8'
);
console.log(`playground/src/pages/stories/model/story-loaders.ts: ${loaders.length} loaders`);
console.log(`total: ${total}`);
